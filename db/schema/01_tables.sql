USE PortfolioViewer
GO

CREATE TABLE APP_USER (
    USER_ID         INT             NOT NULL,
    USERNAME        VARCHAR(20)     NOT NULL,
    PWD_HASH        CHAR(40)        NOT NULL,
    FULL_NAME       VARCHAR(60)     NULL,
    ROLE_CD         VARCHAR(10)     NOT NULL,   -- ADVISER / OPS / ADMIN
    ACTIVE_FLG      CHAR(1)         NOT NULL CONSTRAINT DF_APP_USER_ACTIVE DEFAULT ('Y'),
    LAST_LOGIN_DT   DATETIME        NULL,
    CREATED_DT      DATETIME        NOT NULL CONSTRAINT DF_APP_USER_CREATED DEFAULT (GETDATE()),
    CONSTRAINT PK_APP_USER PRIMARY KEY (USER_ID)
)
GO
CREATE UNIQUE INDEX UX_APP_USER_USERNAME ON APP_USER (USERNAME)
GO

CREATE TABLE CLIENT (
    CLIENT_ID       INT             NOT NULL,
    CLIENT_REF      VARCHAR(12)     NOT NULL,
    CLIENT_NAME     VARCHAR(100)    NOT NULL,
    ADVISER_USER_ID INT             NULL,
    STATUS_CD       CHAR(1)         NOT NULL,   -- A active, D dormant, C closed
    CREATED_DT      DATETIME        NULL,
    CONSTRAINT PK_CLIENT PRIMARY KEY (CLIENT_ID),
    CONSTRAINT FK_CLIENT_ADVISER FOREIGN KEY (ADVISER_USER_ID) REFERENCES APP_USER (USER_ID)
)
GO
CREATE INDEX IX_CLIENT_NAME ON CLIENT (CLIENT_NAME)
GO

CREATE TABLE ACCOUNT (
    ACCT_ID         INT             NOT NULL,
    ACCT_NO         VARCHAR(12)     NOT NULL,
    CLIENT_ID       INT             NOT NULL,
    ACCT_TYPE       VARCHAR(40)     NULL,
    BASE_CCY        CHAR(3)         NOT NULL,
    SAFE_CODE       VARCHAR(10)     NULL,       -- custodian safekeeping a/c
    OPEN_DT         DATETIME        NULL,
    CLOSE_DT        DATETIME        NULL,
    STATUS_CD       CHAR(1)         NOT NULL,   -- O open, C closed
    CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACCT_ID),
    CONSTRAINT FK_ACCOUNT_CLIENT FOREIGN KEY (CLIENT_ID) REFERENCES CLIENT (CLIENT_ID)
)
GO
CREATE INDEX IX_ACCOUNT_CLIENT ON ACCOUNT (CLIENT_ID)
GO

CREATE TABLE INSTRUMENT (
    ISIN            CHAR(12)        NOT NULL,
    INSTR_NAME      VARCHAR(100)    NOT NULL,
    ASSET_CLASS_CD  VARCHAR(4)      NULL,
    CCY             CHAR(3)         NULL,
    SEDOL           VARCHAR(7)      NULL,
    ADDED_DT        DATETIME        NULL,
    CONSTRAINT PK_INSTRUMENT PRIMARY KEY (ISIN)
)
GO

CREATE TABLE RECON_NOTE (
    ACCT_ID         INT             NOT NULL,
    ISIN            CHAR(12)        NOT NULL,
    STMT_DT         DATETIME        NOT NULL,
    STATUS_CD       VARCHAR(10)     NOT NULL,
    NOTE_TXT        VARCHAR(500)    NULL,
    UPDATED_BY      VARCHAR(20)     NULL,
    UPDATED_DT      DATETIME        NULL,
    CONSTRAINT PK_RECON_NOTE PRIMARY KEY (ACCT_ID, ISIN, STMT_DT)
)
GO
